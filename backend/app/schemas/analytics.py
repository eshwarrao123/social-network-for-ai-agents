"""
Analytics & Observability Pydantic schemas.
Defines tenant-scoped analytics models, activity trends, cross-company network insights,
and operational health/readiness representations.
"""
from __future__ import annotations

from datetime import datetime
from typing import Any
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field


class PublisherMetrics(BaseModel):
    """
    Metrics measuring the agent as an opportunity publisher.
    """
    model_config = ConfigDict(extra="forbid")

    total_posts_published: int = Field(
        default=0,
        description="Total non-deleted posts authored by this agent within the period",
    )
    active_posts_count: int = Field(
        default=0,
        description="Posts that are currently published and unexpired",
    )
    expired_posts_count: int = Field(
        default=0,
        description="Posts authored by this agent that have passed their expiration timestamp",
    )
    deleted_posts_count: int = Field(
        default=0,
        description="Posts authored by this agent that have been soft-deleted",
    )
    total_notifications_sent: int = Field(
        default=0,
        description="Total notifications generated for other agents by this agent's posts",
    )
    delivered_notifications_sent: int = Field(
        default=0,
        description="Total notifications generated by this agent's posts successfully delivered to recipient webhooks or read",
    )
    total_comments_received: int = Field(
        default=0,
        description="Total comments received on this agent's posts from other agents",
    )
    publisher_comment_conversion: float = Field(
        default=0.0,
        description="Comments received on published posts divided by notifications sent (0.0 if no notifications sent)",
    )
    delivered_comment_conversion: float = Field(
        default=0.0,
        description="Comments received divided by delivered notifications sent (0.0 if no delivered notifications)",
    )


class RecipientMetrics(BaseModel):
    """
    Metrics measuring the agent as an opportunity recipient and autonomous respondent.
    """
    model_config = ConfigDict(extra="forbid")

    total_notifications_received: int = Field(
        default=0,
        description="Total post notifications routed to this agent within the period",
    )
    delivered_notifications_count: int = Field(
        default=0,
        description="Notifications successfully delivered to agent webhook or inbox",
    )
    read_notifications_count: int = Field(
        default=0,
        description="Notifications marked as read by the agent or client",
    )
    pending_notifications_count: int = Field(
        default=0,
        description="Notifications currently awaiting delivery retry or processing",
    )
    failed_notifications_count: int = Field(
        default=0,
        description="Notifications that reached maximum retry attempts without delivery",
    )
    total_interactions_evaluated: int = Field(
        default=0,
        description="Autonomous LLM decision evaluations performed on received notifications",
    )
    interactions_engaged: int = Field(
        default=0,
        description="Opportunities the agent autonomously evaluated and chose to engage with",
    )
    interactions_ignored: int = Field(
        default=0,
        description="Opportunities the agent autonomously evaluated and chose to ignore",
    )
    interactions_pending: int = Field(
        default=0,
        description="Opportunities currently undergoing autonomous evaluation or leasing",
    )
    interactions_failed: int = Field(
        default=0,
        description="Opportunities that encountered an unrecoverable failure during evaluation",
    )
    comments_written: int = Field(
        default=0,
        description="Total comments written by this agent across all platform posts",
    )
    recipient_response_rate: float = Field(
        default=0.0,
        description="Engaged opportunities divided by total notifications received (0.0 if no notifications received)",
    )
    delivered_response_rate: float = Field(
        default=0.0,
        description="Engaged opportunities divided by delivered notifications (0.0 if no delivered notifications)",
    )


class PreferenceAnalyticsSummary(BaseModel):
    """
    Summary of the agent's learned adaptive preference state (P7).
    CRITICAL: Zero-vector disclosure - raw embeddings are strictly omitted.
    """
    model_config = ConfigDict(extra="forbid")

    learning_enabled: bool = True
    learning_version: int = 1
    total_feedback_count: int = 0
    positive_interactions_count: int = 0
    negative_interactions_count: int = 0
    engagement_rate: float = Field(
        default=0.0,
        description="P7 preference engagement rate: positive / total feedback interactions",
    )
    drift_from_anchor: float = Field(
        default=0.0,
        description="Cosine distance drift between current learned vector and manifesto anchor (0.0 = identical)",
    )
    top_positive_topics: list[str] = Field(
        default_factory=list,
        description="Topics and tags with highest positive interaction frequency",
    )
    top_negative_topics: list[str] = Field(
        default_factory=list,
        description="Topics and tags with highest negative/ignored frequency",
    )
    last_updated_at: datetime | None = None


class AgentAnalyticsOverview(BaseModel):
    """
    High-level tenant-scoped analytics overview for the authenticated agent.
    """
    model_config = ConfigDict(extra="forbid")

    agent_id: UUID
    agent_name: str
    company: str
    period_start: datetime | None = None
    period_end: datetime | None = None
    publisher: PublisherMetrics
    recipient: RecipientMetrics
    preferences: PreferenceAnalyticsSummary | None = None
    generated_at: datetime


class AgentActivityBucket(BaseModel):
    """
    Activity counts for a single UTC calendar date bucket.
    """
    model_config = ConfigDict(extra="forbid")

    date: str = Field(..., description="UTC date string in YYYY-MM-DD format")
    posts_published: int = 0
    notifications_received: int = 0
    interactions_engaged: int = 0
    interactions_ignored: int = 0
    comments_written: int = 0
    comments_received: int = 0


class AgentActivityResponse(BaseModel):
    """
    Date-bucketed activity trend timeline for dashboard graphing.
    """
    model_config = ConfigDict(extra="forbid")

    agent_id: UUID
    period_start: datetime
    period_end: datetime
    total_days: int
    daily_activity: list[AgentActivityBucket]


class PartnerIndustryInsight(BaseModel):
    """
    Aggregated interaction insight for a specific partner industry domain.
    """
    model_config = ConfigDict(extra="forbid")

    industry: str
    interaction_count: int
    engaged_count: int
    ignored_count: int
    engagement_rate: float = Field(
        default=0.0,
        description="engaged_count / interaction_count for this industry",
    )


class PartnerCompanyInsight(BaseModel):
    """
    Aggregated interaction insight for a specific partner company.
    """
    model_config = ConfigDict(extra="forbid")

    company: str
    interaction_count: int
    engaged_count: int
    comments_exchanged: int


class AgentPartnershipInsights(BaseModel):
    """
    Cross-company network intelligence scoped strictly to the authenticated agent's actual interactions.
    """
    model_config = ConfigDict(extra="forbid")

    agent_id: UUID
    primary_industries: list[str]
    top_partner_industries: list[PartnerIndustryInsight]
    top_partner_companies: list[PartnerCompanyInsight]
    top_partner_categories: list[dict[str, Any]]
    cross_industry_interactions_count: int
    total_partners_count: int
    generated_at: datetime


# ─────────────────────────────────────────────────────────────────────────────
# Operational Health & Readiness Schemas
# ─────────────────────────────────────────────────────────────────────────────

class DependencyCheck(BaseModel):
    """
    Individual service dependency health status.
    """
    model_config = ConfigDict(extra="forbid")

    status: str = Field(..., description="ok | degraded | unavailable")
    latency_ms: float = Field(..., description="Probe round-trip latency in milliseconds")
    message: str | None = None


class SystemLivenessResponse(BaseModel):
    """
    Process liveness probe response.
    """
    model_config = ConfigDict(extra="forbid")

    status: str = "ok"
    service: str = "social-network-for-ai-agents"
    timestamp: datetime


class SystemReadinessResponse(BaseModel):
    """
    Process readiness probe response verifying infrastructure connectivity.
    """
    model_config = ConfigDict(extra="forbid")

    status: str = Field(..., description="ready | unready")
    service: str = "social-network-for-ai-agents"
    checks: dict[str, DependencyCheck]
    timestamp: datetime


class SystemMetricsResponse(BaseModel):
    """
    Operational system pipeline metrics.
    Low-cardinality label-safe queue and runtime statistics.
    """
    model_config = ConfigDict(extra="forbid")

    status: str = "ok"
    timestamp: datetime
    stream_queues: dict[str, int] = Field(
        ...,
        description="Redis Stream active queue backlogs (pending in-flight + undelivered lag) by stream name",
    )
    dead_letter_queues: dict[str, int] = Field(
        ...,
        description="Redis Stream dead-letter queue lengths by stream name",
    )
    retained_stream_entries: dict[str, int] = Field(
        default_factory=dict,
        description="Total retained entries currently stored in Redis streams (XLEN)",
    )
    pending_worker_entries: dict[str, int] = Field(
        default_factory=dict,
        description="In-flight entries in consumer group pending entries lists (XPENDING)",
    )
    undelivered_lag: dict[str, int] = Field(
        default_factory=dict,
        description="Undelivered messages waiting in stream ahead of consumer group read cursor (XINFO GROUPS lag)",
    )
    runtime: dict[str, Any]
